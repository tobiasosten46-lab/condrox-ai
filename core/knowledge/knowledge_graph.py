"""
Knowledge Graph — semantic link layer on top of KnowledgeBackend.

Builds a graph where nodes are KnowledgeItem instances and edges represent
token-overlap (Jaccard) similarity. The graph is used to expand BM25 results
with related knowledge items that may not directly match the query terms.

Mathematical Foundation:
- Jaccard similarity: J(A, B) = |A ∩ B| / |A ∪ B|
- Graph expansion: score(n) = Σ (edge_strength(n, s) * overlap(n, query))
- Top-k retrieval uses a bounded min-heap: O(d log k) for d neighbors.

Copyright 2026 Tobias Østen. Licensed under Apache License 2.0.
"""

from __future__ import annotations

import heapq
from collections import defaultdict
from dataclasses import dataclass
from itertools import combinations
from typing import Dict, Iterable, List, Optional, Set, Tuple

from core.knowledge.knowledge_backend import KnowledgeBackend
from core.knowledge.knowledge_models import KnowledgeItem


@dataclass(frozen=True, slots=True)
class KnowledgeGraphNode:
    """
    Immutable node in the knowledge graph.

    Attributes:
        node_id: The underlying KnowledgeItem.item_id.
        content: The underlying knowledge content.
        domain: The knowledge domain.
        tokens: Frozen set of normalized tokens.
        token_count: Number of unique tokens.

    Complexity: S(n) ∈ O(t) where t is the number of unique tokens.
    """

    node_id: str
    content: str
    domain: str
    tokens: frozenset[str]
    token_count: int


@dataclass(frozen=True, slots=True)
class KnowledgeGraphEdge:
    """
    Immutable edge between two knowledge nodes.

    Attributes:
        source: Source node ID.
        target: Target node ID.
        relation: Relation label (default 'related').
        strength: Edge strength in [0.0, 1.0].

    Complexity: S(n) ∈ O(1).
    """

    source: str
    target: str
    relation: str
    strength: float


class KnowledgeGraph:
    """
    Graph-structured knowledge layer with Jaccard-based edges.

    The graph is built from a KnowledgeBackend instance and used to expand
    retrieval results beyond pure BM25 matches. All public methods are
    stateless with respect to the backend after build() completes.

    Attributes:
        _nodes: Mapping from node_id to KnowledgeGraphNode.
        _edges: Mapping from canonical (min, max) node_id pair to edge.
        _adjacency: Adjacency list with neighbor id and edge strength.

    Complexity:
        build: T(n) ∈ O(Σ p_t) where p_t is candidate pairs generated by token t.
        expand: T(n) ∈ O(d log k) for d explored neighbors and top_k results.
        search: T(n) ∈ O(q·df·log k + d log k) when graph is built.
    """

    __slots__ = ("_nodes", "_edges", "_adjacency", "_built")

    def __init__(self) -> None:
        """Initialize an empty knowledge graph.

        Complexity: T(n) ∈ O(1), S(n) ∈ O(1).
        """
        self._nodes: Dict[str, KnowledgeGraphNode] = {}
        self._edges: Dict[Tuple[str, str], KnowledgeGraphEdge] = {}
        self._adjacency: Dict[str, List[Tuple[str, float]]] = defaultdict(list)
        self._built: bool = False

    @property
    def is_built(self) -> bool:
        """Return whether the graph has been built.

        Complexity: T(n) ∈ O(1), S(n) ∈ O(1).
        """
        return self._built

    @staticmethod
    def _tokenize(text: str) -> List[str]:
        """Tokenize text using the same stemming rules as KnowledgeBackend.

        Reuses KnowledgeBackend.tokenize to guarantee token consistency.

        Complexity: T(n) ∈ O(n) where n is text length.
        """
        return KnowledgeBackend.tokenize(text)

    def add_item(self, item: KnowledgeItem) -> None:
        """Add a KnowledgeItem as a graph node.

        Args:
            item: Knowledge item to add.

        Complexity: T(n) ∈ O(n) for token extraction, S(n) ∈ O(t).
        """
        tokens = frozenset(self._tokenize(item.content))
        node = KnowledgeGraphNode(
            node_id=item.item_id,
            content=item.content,
            domain=item.domain,
            tokens=tokens,
            token_count=len(tokens),
        )
        self._nodes[item.item_id] = node

    def build(
        self,
        backend: KnowledgeBackend,
        min_jaccard: float = 0.15,
        max_edges_per_node: int = 20,
        max_posting_size: int = 1000,
    ) -> None:
        """Build the knowledge graph from a backend.

        Uses an inverted index over node tokens to generate candidate pairs,
        then computes Jaccard similarity and keeps the strongest edges per node.

        Args:
            backend: KnowledgeBackend to ingest items from.
            min_jaccard: Minimum Jaccard similarity to create an edge.
            max_edges_per_node: Maximum edges retained per node.
            max_posting_size: Skip tokens that appear in more than this many
                documents to avoid combinatorial explosions.

        Complexity: T(n) ∈ O(i + Σ p_t + e log m) where i = items,
            p_t = candidate pairs for token t, e = generated edges,
            m = max_edges_per_node.
        """
        self._nodes.clear()
        self._edges.clear()
        self._adjacency.clear()

        # Ingest all backend items as nodes.
        for item in backend.items():
            self.add_item(item)

        if len(self._nodes) < 2:
            self._built = len(self._nodes) >= 0
            return

        # Build token -> node postings.
        token_to_nodes: Dict[str, List[str]] = defaultdict(list)
        for node_id, node in self._nodes.items():
            for token in node.tokens:
                token_to_nodes[token].append(node_id)

        # Accumulate overlap counts for candidate pairs.
        overlap_counts: Dict[Tuple[str, str], int] = defaultdict(int)
        for token, node_ids in token_to_nodes.items():
            if len(node_ids) > max_posting_size:
                # Too common to be discriminative; skip to keep complexity bounded.
                continue
            for a, b in combinations(node_ids, 2):
                if a > b:
                    a, b = b, a
                overlap_counts[(a, b)] += 1

        # Compute Jaccard and collect candidate edges per node.
        edges_per_node: Dict[str, List[Tuple[str, float]]] = defaultdict(list)
        for (a, b), overlap in overlap_counts.items():
            node_a = self._nodes[a]
            node_b = self._nodes[b]
            union_size = len(node_a.tokens | node_b.tokens)
            if union_size == 0:
                continue
            jaccard = overlap / union_size
            if jaccard >= min_jaccard:
                edges_per_node[a].append((b, jaccard))
                edges_per_node[b].append((a, jaccard))

        # Keep only the top edges per node and add them bidirectionally.
        for node_id, candidates in edges_per_node.items():
            candidates.sort(key=lambda x: x[1], reverse=True)
            for target, strength in candidates[:max_edges_per_node]:
                self._add_edge(node_id, target, "related", strength)

        self._built = True

    def _add_edge(
        self, source: str, target: str, relation: str, strength: float
    ) -> Optional[KnowledgeGraphEdge]:
        """Add an undirected edge between two nodes.

        Args:
            source: Source node ID.
            target: Target node ID.
            relation: Edge relation label.
            strength: Edge strength in [0.0, 1.0].

        Returns:
            The created edge, or None if source == target.

        Complexity: T(n) ∈ O(1), S(n) ∈ O(1).
        """
        if source == target:
            return None
        key = (source, target) if source < target else (target, source)
        if key in self._edges:
            return self._edges[key]
        edge = KnowledgeGraphEdge(
            source=source,
            target=target,
            relation=relation,
            strength=float(max(0.0, min(1.0, strength))),
        )
        self._edges[key] = edge
        self._adjacency[source].append((target, edge.strength))
        self._adjacency[target].append((source, edge.strength))
        return edge

    def expand(
        self,
        seed_ids: Iterable[str],
        query: str,
        top_k: int = 5,
        max_hops: int = 1,
    ) -> List[Tuple[str, float]]:
        """Expand seed nodes via graph neighbors.

        Args:
            seed_ids: Starting node IDs (typically BM25 results).
            query: Raw query string used to score neighbor relevance.
            top_k: Maximum number of neighbors to return.
            max_hops: Number of graph hops to explore (1 or 2 recommended).

        Returns:
            List of (node_id, combined_score) sorted by descending score.

        Complexity: T(n) ∈ O(d log k) for d explored neighbors.
        """
        if not self.is_built or not self._nodes:
            return []

        query_tokens = frozenset(self._tokenize(query))
        if not query_tokens:
            return []

        visited: Set[str] = set(seed_ids)
        frontier: Set[str] = set(seed_ids)
        scores: Dict[str, float] = {}

        for _ in range(max_hops):
            next_frontier: Set[str] = set()
            for node_id in frontier:
                node = self._nodes.get(node_id)
                if node is None:
                    continue
                for neighbor, edge_strength in self._adjacency.get(node_id, []):
                    if neighbor in visited:
                        continue
                    neighbor_node = self._nodes.get(neighbor)
                    if neighbor_node is None:
                        continue
                    overlap = len(query_tokens & neighbor_node.tokens)
                    relevance = overlap / max(len(query_tokens), 1)
                    combined = edge_strength * relevance
                    if neighbor in scores:
                        scores[neighbor] = max(scores[neighbor], combined)
                    else:
                        scores[neighbor] = combined
                    next_frontier.add(neighbor)
                    visited.add(neighbor)
            frontier = next_frontier
            if not frontier:
                break

        if not scores:
            return []

        heap: List[Tuple[float, int, str]] = []
        counter = 0
        for node_id, score in scores.items():
            entry = (score, counter, node_id)
            if len(heap) < top_k:
                heapq.heappush(heap, entry)
            elif score > heap[0][0]:
                heapq.heapreplace(heap, entry)
            counter += 1

        heap.sort(key=lambda x: x[0], reverse=True)
        return [(node_id, score) for score, _, node_id in heap]

    def search(
        self,
        backend: KnowledgeBackend,
        query: str,
        top_k: int = 5,
        domain_filter: Optional[str] = None,
    ) -> List[KnowledgeItem]:
        """Search backend and expand results through the graph.

        Args:
            backend: KnowledgeBackend to search.
            query: Query string.
            top_k: Maximum total results after expansion.
            domain_filter: Optional domain constraint.

        Returns:
            Top-k KnowledgeItem instances sorted by combined score.

        Complexity: T(n) ∈ O(q·df·log k + d log k).
        """
        if not self.is_built or not self._nodes:
            return backend.search(query, top_k=top_k, domain_filter=domain_filter)

        bm25_items = backend.search(
            query, top_k=top_k, domain_filter=domain_filter
        )
        seed_ids = [item.item_id for item in bm25_items]

        if not seed_ids:
            return bm25_items

        expanded = self.expand(
            seed_ids=seed_ids,
            query=query,
            top_k=max(top_k, len(seed_ids) + 3),
            max_hops=1,
        )

        # Combine BM25 presence with graph relevance scores.
        combined_scores: Dict[str, float] = {item.item_id: 1.0 for item in bm25_items}
        for node_id, graph_score in expanded:
            combined_scores[node_id] = combined_scores.get(node_id, 0.0) + graph_score

        sorted_ids = sorted(
            combined_scores,
            key=lambda item_id: combined_scores[item_id],
            reverse=True,
        )[:top_k]

        result: List[KnowledgeItem] = []
        for item_id in sorted_ids:
            item = backend.get(item_id)
            if item is not None:
                result.append(item)
        return result
